/**
 * Build the interface as static files for packaging inside the Android app.
 *
 *   npm run app:shell
 *
 * The packaged app is not a browser pointed at the website. The whole
 * interface is compiled to plain HTML, CSS and JavaScript and shipped inside
 * the APK, so it opens from local storage with no network round trip. Only the
 * hazard data is fetched, from the deployed site, because that data is live
 * and a disaster app carrying a frozen copy would be worse than useless.
 *
 * Two things have to change for a static export, and both are handled here so
 * the normal `npm run build` is untouched:
 *
 *   1. The API routes cannot be exported; they are server handlers by nature.
 *      They are not needed either, since the app calls the deployed site. The
 *      directory is temporarily renamed to a private name (a leading
 *      underscore), which Next excludes from routing.
 *
 *   2. next/image has no optimiser in a static export, so images are marked
 *      unoptimised for this build only.
 *
 * The rename is restored in a finally block, including on Ctrl+C, so an
 * interrupted build cannot leave the source tree broken.
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const apiDir = join(root, "src", "app", "api");
const apiHidden = join(root, "src", "app", "_api_excluded_from_export");
const realConfig = join(root, "next.config.ts");
const configBackup = join(root, "next.config.web.ts.bak");
const outDir = join(root, "out");
const shellDir = join(root, "android-app-shell");

const SITE =
  process.env.NEXT_PUBLIC_API_BASE ?? "https://disasteralert.ankitgupta.com.np";

let renamed = false;

function restore() {
  if (renamed && existsSync(apiHidden)) {
    renameSync(apiHidden, apiDir);
    renamed = false;
    console.log("restored src/app/api");
  }
  // Put the real config back, whatever happened.
  if (existsSync(configBackup)) {
    rmSync(realConfig, { force: true });
    renameSync(configBackup, realConfig);
    console.log("restored next.config.ts");
  }
}

// An interrupted build must not leave the API routes renamed.
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => {
    restore();
    process.exit(1);
  });
}

try {
  if (existsSync(apiHidden)) {
    throw new Error(
      `${apiHidden} already exists. A previous build was interrupted; ` +
        "rename it back to src/app/api before retrying.",
    );
  }

  // This Next version has no --config flag, so the config file itself is
  // swapped and restored in the finally block.
  renameSync(realConfig, configBackup);
  writeFileSync(
    realConfig,
    `import type { NextConfig } from "next";

/**
 * Generated by scripts/build-app-shell.mjs. Do not edit or commit.
 * Static export configuration for the packaged Android app.
 */
const nextConfig: NextConfig = {
  output: "export",
  // No image optimiser exists in a static export.
  images: { unoptimized: true },
  // Directory-style URLs so the WebView resolves /incidents to
  // /incidents/index.html from the local filesystem.
  trailingSlash: true,
  poweredByHeader: false,
  reactStrictMode: true,
};

export default nextConfig;
`,
    "utf8",
  );

  console.log("> Excluding API routes from the export");
  renameSync(apiDir, apiHidden);
  renamed = true;

  // Next keeps generated route types under .next and they still reference the
  // routes just hidden, which fails the type check. A clean build directory is
  // the simplest fix and costs only a recompile.
  rmSync(join(root, ".next"), { recursive: true, force: true });

  console.log(`> Building static shell against ${SITE}\n`);
  execFileSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    ["next", "build"],
    {
      cwd: root,
      stdio: "inherit",
      shell: process.platform === "win32",
      env: {
        ...process.env,
        NEXT_PUBLIC_API_BASE: SITE,
        // Skip the linter here; `npm run build` already gates on it.
        NEXT_TELEMETRY_DISABLED: "1",
      },
    },
  );

  if (!existsSync(outDir)) {
    throw new Error("next build produced no out/ directory");
  }

  // The QR code and social card serve the website only; no need to ship them
  // inside the app.
  rmSync(join(outDir, "install-qr.png"), { force: true });
  rmSync(join(outDir, "og-card.png"), { force: true });
  // 1.3MB, and only ever read by scripts/generate-icons.mjs at build time.
  rmSync(join(outDir, "logo.png"), { force: true });

  rmSync(shellDir, { recursive: true, force: true });
  cpSync(outDir, shellDir, { recursive: true });

  console.log(`
  Static shell written to android-app-shell/
  Data will be fetched from ${SITE}

  Next: npx cap sync android && npm run apk
`);
} finally {
  restore();
}
